"""Write the setup tables of Ch. 6 from the run configs, the experiment index and the code.

Input:  results/experiment_index.csv, each reported run's config.yaml, and a few
        constants that are code defaults (checked against code/ by regular expression).
Output: thesis/tables/ch6_experiments.tex   overview of the experiments
        thesis/tables/ch6_hparams.tex       training and evaluation settings shared by all runs
        thesis/tables/ch6_strategy_params.tex  parameters of each strategy
        All are bare `tabular` bodies (booktabs); caption and label are in the chapter.

Every value shared by all runs is checked to be identical in every reported run's
config; the script stops if a run deviates, instead of printing a wrong table.

Usage (from the repository root):
    python scripts/make_setup_tables.py
"""
from __future__ import annotations

import csv
import math
import re

from _common import INDEX_FILE, REPO, read_config
from _results import STRATEGY, STRATEGY_ORDER, TABLES, FULL_TRAIN_VOLUMES

CODE = REPO / "code" / "src"
HEADER = "% Generated by scripts/make_setup_tables.py. Do not edit."

# Experiment groups (index column 'role') -> description, research objective, section label.
GROUPS = [
    ("Main", "Comparison of the strategies", "2", "sec:exp-main"),
    ("Rank Ablation", "LoRA rank", "4", "sec:exp-rank"),
    ("Convergence Diagnosis", "Diagnosis of the patellar failure", "4", "sec:exp-patellar"),
    ("Few-shot", "Amount of labelled data", "3", "sec:exp-few-shot"),
    ("Task Order Ablation", "Task order", "4", "sec:exp-task-order"),
    ("Replay Ablation", "Replay", "4", "sec:exp-main"),
    # Reruns of October 2026. Section labels provisional until the rerun parts of Ch. 6 are written.
    ("Scaling Ablation", "Gradient scaling of the prompt-tuning strategy", "4", "sec:exp-main"),
    ("Equal Updates", "Amount of labelled data with the update count of the full data", "3", "sec:exp-few-shot"),
    ("Joint Reference", "Upper reference: joint fine-tuning", "2, 3", "sec:exp-main"),
]
# The single-task diagnosis (role "Convergence Diagnosis") is reported in Ch. 6 (decision 2026-10-22,
# revising the earlier plan to put it in the Discussion). Order of the strategies as in Ch. 5.4.
TABLE_ORDER = ["naive_sequential_finetuning", "lora", "shared_lora", "zscl", "cpe_clip", "joint_fine_tuning"]

# Code defaults that are not in the run configs: (description, file, pattern that must match).
CODE_DEFAULTS = {
    "fg": ("foreground patch fraction 0.85", CODE / "data" / "dataset.py",
           r"foreground_patch_fraction:\s*float\s*=\s*0\.85"),
    "loss": ("BCE and Dice weights 1:1", CODE / "training" / "losses.py",
             r"bce_weight:\s*float\s*=\s*1\.0[\s\S]*dice_weight:\s*float\s*=\s*1\.0"),
    "step": ("sliding-window step 0.5", CODE / "inference" / "sliding_window.py",
             r"tile_step_size:\s*float\s*=\s*0\.5"),
    "sigma": ("Gaussian sigma 1/8", CODE / "inference" / "sliding_window.py", r"sigma_scale=1\.0\s*/\s*8"),
    "thr": ("threshold 0.5", CODE / "evaluation" / "test.py", r"probs\s*>\s*0\.5"),
}


def check_code_defaults():
    for key, (what, path, pattern) in CODE_DEFAULTS.items():
        if not re.search(pattern, path.read_text(encoding="utf-8")):
            raise SystemExit(f"code default not found ({what}) in {path.relative_to(REPO)}")


def reported_runs():
    with open(INDEX_FILE, newline="", encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r["role"] and r["role"] != "excluded"]
    for r in rows:
        r["config"] = read_config(REPO / r["path"] / "config.yaml")
    return rows


def get(cfg, *keys):
    for k in keys:
        cfg = cfg[k]
    return cfg


def uniform(runs, *keys):
    values = {repr(get(r["config"], *keys)) for r in runs}
    if len(values) != 1:
        raise SystemExit(f"{'.'.join(keys)} differs between reported runs: {values}")
    return get(runs[0]["config"], *keys)


def roles(run):
    return [x for x in run["role"].split(";") if x]


def num(x) -> str:
    """LaTeX number: 1e-4 -> 10^{-4}, 3e-05 -> 3 \\cdot 10^{-5}."""
    x = float(x)
    if x == 0 or 1e-3 <= abs(x) < 1e4:
        return f"{x:g}"
    m, e = f"{x:e}".split("e")
    m = float(m)
    return (f"10^{{{int(e)}}}" if m == 1 else f"{m:g} \\cdot 10^{{{int(e)}}}")


def name(strategy):
    return STRATEGY[strategy][0]


def joined(values):
    values = list(values)
    return values[0] if len(values) == 1 else ", ".join(values[:-1]) + " and " + values[-1]


def experiments_table(runs):
    lines = [HEADER, r"\small\setlength{\tabcolsep}{4pt}",
             r"\begin{tabularx}{\linewidth}{@{}>{\raggedright\arraybackslash}p{3.1cm}"
             r">{\raggedright\arraybackslash}X >{\raggedright\arraybackslash}p{1.9cm} c c@{}}",
             r"\toprule",
             r"Experiment & Strategies and configurations & Training volumes per task & Objective & Section \\",
             r"\midrule"]
    for role, title, objective, label in GROUPS:
        group = [r for r in runs if role in roles(r)]
        if not group:
            continue
        configs = []
        for s in TABLE_ORDER:
            g = [r for r in group if r["strategy"] == s]
            if not g:
                continue
            ranks = sorted({int(r["lora_rank"]) for r in g if r["lora_rank"]})
            desc = name(s)
            if ranks:
                desc += " ($r = " + ", ".join(map(str, ranks)) + "$)"
            if role == "Convergence Diagnosis":
                # Single task; one setting changed per run (rank, learning rate, seed or epochs).
                desc += ", patellar cartilage only; rank, learning rate, seed or number of epochs changed"
                configs.append(desc)
                continue
            orders = sorted({r["task_order"] for r in g} - {"original", "joint"})   # joint: no task order
            if orders:
                desc += " in " + joined(["original"] + orders) + " order"
            if any(r["replay_fraction"] for r in g):
                desc += " with and without replay"
            if role == "Scaling Ablation":
                desc += " without per-task gradient scaling"
            if role == "Equal Updates":
                desc += ", " + joined(sorted({r["epochs"] for r in g})) + " epochs per task"
            configs.append(desc)
        volumes = sorted({int(r["train_max_cases"]) if r["train_max_cases"] else FULL_TRAIN_VOLUMES
                          for r in group} | ({FULL_TRAIN_VOLUMES} if role == "Few-shot" else set()))
        lines.append(f"{title} & {'; '.join(configs)} & {', '.join(map(str, volumes))} & {objective} & "
                     rf"\ref{{{label}}} \\")
    lines += [r"\bottomrule", r"\end{tabularx}"]
    return "\n".join(lines) + "\n"


def hparams_table(runs):
    # The single-task diagnosis run uses its own training length; it is described with that run.
    runs = [r for r in runs if "Convergence Diagnosis" not in roles(r)]
    # The equal-updates runs differ only in the number of epochs and the validation interval
    # (checked here); all other settings are checked together with the other runs.
    equal = [r for r in runs if "Equal Updates" in roles(r)]
    others = [r for r in runs if "Equal Updates" not in roles(r)]
    epochs = uniform(others, "training", "epochs")
    if any(get(r["config"], "training").get("validation_interval", 1) != 1 for r in others):
        raise SystemExit("validation_interval differs from 1 in a run outside the equal-updates experiment")
    epochs_text = f"{epochs}"
    if equal:
        e_eq = uniform(equal, "training", "epochs")
        v_eq = uniform(equal, "training", "validation_interval")
        epochs_text += f"; {e_eq} in the equal-updates runs (validation every {v_eq} epochs)"
    t = lambda *k: uniform(runs, "training", *k)
    patch = uniform(runs, "dataset", "patch_size")
    if uniform(runs, "model", "deep_supervision") is not False:
        raise SystemExit("deep supervision is not off in every run")
    opt = ("SGD, Nesterov" if t("optimizer", "nesterov") else "SGD")
    rows = [
        ("Optimiser", "", opt),
        ("Initial learning rate", r"$\eta_0$", f"${num(t('optimizer', 'lr'))}$"),
        ("Momentum", r"$\mu$", f"${num(t('optimizer', 'momentum'))}$"),
        ("Weight decay", r"$\omega$", f"${num(t('optimizer', 'weight_decay'))}$"),
        ("Learning-rate schedule", "", f"polynomial, exponent {num(t('optimizer', 'poly_power'))}, per iteration, "
                                       "restarted for every task"),
        ("Epochs per task", "$E$", epochs_text),
        ("Batch size", "", f"{uniform(runs, 'dataset', 'batch_size')}"),
        ("Patch size (voxels)", "", f"${patch[0]} \\times {patch[1]} \\times {patch[2]}$"),
        ("Foreground-centred patches", r"$\pi_{\mathrm{fg}}$", "0.85"),
        ("Loss", r"$\mathcal{L}_{\mathrm{seg}}$", "binary cross-entropy + Dice, weights 1:1"),
        ("Deep supervision", "", "off"),
        ("Data augmentation", "", "none"),
        ("Random seed (training, split)", "", f"{t('seed')}, {uniform(runs, 'dataset', 'seed')}"),
        ("Sliding-window step", "", "0.5 of the patch size"),
        ("Gaussian weighting", "", "standard deviation 1/8 of the patch size"),
        ("Probability threshold", "", "0.5"),
    ]
    lines = [HEADER, r"\small", r"\begin{tabular}{@{}ll>{\raggedright\arraybackslash}p{6.4cm}@{}}", r"\toprule",
             r"Setting & Symbol & Value \\", r"\midrule"]
    lines += [f"{a} & {b} & {c} \\\\" for a, b, c in rows]
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def strategy_table(runs):
    rows = []
    for s in TABLE_ORDER:
        g = [r for r in runs if r["strategy"] == s and "Convergence Diagnosis" not in roles(r)]
        if not g:
            continue
        reps = [r["config"]["continual"]["replay_memory"] for r in g
                if r["config"]["continual"].get("replay_memory", {}).get("enabled")]
        cont = [r["config"]["continual"] for r in g if not r["config"]["continual"].get("replay_memory", {}).get("enabled")]
        if s in ("lora", "shared_lora"):
            alphas = {c["lora"]["alpha"] for c in cont}
            drops = {c["lora"]["dropout"] for c in cont}
            if len(alphas) != 1 or len(drops) != 1:
                raise SystemExit(f"{s}: alpha or dropout differs between runs")
            alpha, drop = alphas.pop(), drops.pop()
            ranks = sorted({int(c["lora"]["rank"]) for c in cont})
            main = [int(r["lora_rank"]) for r in g if "Main" in roles(r)]
            parts = sorted({p for c in cont for p in c["lora"]["attn_parts"]})
            gam = ", ".join(f"{alpha / math.sqrt(k):.2f}".rstrip("0").rstrip(".") for k in ranks)
            # The rank used in the comparison of the strategies is set in bold.
            rows.append((name(s), "Rank", "$r$", ", ".join(rf"\textbf{{{k}}}" if k in main else str(k)
                                                            for k in ranks)))
            rows.append(("", "Scaling constant", r"$\alpha$", f"{num(alpha)}"))
            rows.append(("", "Scaling factor", r"$\gamma_r$", gam))
            rows.append(("", "Dropout (low-rank path)", "", f"{num(drop)}"))
            rows.append(("", "Adapted projections", "",
                         "$" + ", ".join(rf"\mat{{W}}_{p}" for p in parts) + "$, cross-attention"))
            if reps:
                fr = {r_["fraction"] for r_ in reps}
                mx = {r_["max_size"] for r_ in reps}
                rk = sorted({int(r["lora_rank"]) for r in g if r["replay_fraction"]})
                rows.append(("Shared LoRA + replay", "Rank (otherwise as shared LoRA)", "$r$",
                             ", ".join(map(str, rk))))
                rows.append(("", "Replay fraction", r"$\rho$", ", ".join(num(x) for x in sorted(fr))))
                rows.append(("", "Maximum memory size", r"$M_{\max}$", ", ".join(map(str, sorted(mx)))))
        elif s == "zscl":
            z = {(c["zscl"]["distillation_weight"], c["zscl"]["weight_ensemble_interval"]) for c in cont}
            if len(z) != 1:
                raise SystemExit("zscl parameters differ between runs")
            lam, interval = z.pop()
            rows.append((name(s), "Distillation weight", r"$\lambda$", f"${num(lam)}$"))
            rows.append(("", "Ensemble interval (iterations)", r"$I_{\mathrm{we}}$", f"{interval}"))
        elif s == "cpe_clip":
            p = {(c["cpe_clip"]["prompt_tokens"], c["cpe_clip"]["prompt_layers"], c["cpe_clip"]["alpha_floor"])
                 for c in cont}
            if len(p) != 1:
                raise SystemExit("cpe_clip parameters differ between runs")
            m, lp, floor = p.pop()
            rows.append((name(s), "Learned prompt tokens per layer", "$m$", f"{m}"))
            rows.append(("", "Prompted decoder layers", "$L_p$", f"{lp}"))
            rows.append(("", "Gradient-scale lower bound", "", f"{num(floor)}"))
    lines = [HEADER, r"\small",
             r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{2.6cm}ll>{\raggedright\arraybackslash}p{4.4cm}@{}}",
             r"\toprule",
             r"Strategy & Parameter & Symbol & Value \\", r"\midrule"]
    for k, (a, b, c, d) in enumerate(rows):
        if a and k:
            lines.append(r"\addlinespace")
        lines.append(f"{a} & {b} & {c} & {d} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def main():
    check_code_defaults()
    runs = reported_runs()
    for fname, tex in [("ch6_experiments", experiments_table(runs)),
                       ("ch6_hparams", hparams_table(runs)),
                       ("ch6_strategy_params", strategy_table(runs))]:
        path = TABLES / f"{fname}.tex"
        path.write_text(tex, encoding="utf-8")
        print(f"Wrote {path.relative_to(REPO)}")


if __name__ == "__main__":
    main()
