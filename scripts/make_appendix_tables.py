"""Write the appendix tables: training/test volumes and the evaluation matrix of every reported run.

Input:  results/experiment_index.csv, each run's eval_matrix.csv and tasks/*/logs/run.log,
        thesis/tables/per_volume_dice.csv (test volumes).
Output: thesis/tables/appA_volumes.tex   few-shot training sets and test volumes (bare tabularx)
        thesis/tables/appA_matrices.tex  one non-floating table per run (\\captionof, not listed
                                         in the list of tables), grouped by experiment

The few-shot sets are read from the '[DATA] img=...' lines of the training logs: in a few-shot
run every epoch draws each of its k volumes once, so the set of logged volumes is the training
set. The script checks that all runs and tasks with the same k used the same set and that the
sets are nested.

Usage (from the repository root):
    python scripts/make_appendix_tables.py
"""
from __future__ import annotations

import csv
import re
from pathlib import Path

from _common import INDEX_FILE, REPO
from _results import STRATEGY, STRATEGY_ORDER, TABLES, TASK_SHORT

HEADER = "% Generated by scripts/make_appendix_tables.py. Do not edit."
DATA_RE = re.compile(r"\[DATA\] img=\['[^']*/(MTR_\d+)\.nii\.gz'\]")
GROUPS = [("Main", "Comparison of the strategies"), ("Rank Ablation", "LoRA rank"),
          ("Convergence Diagnosis", "Diagnosis of the patellar failure"),
          ("Few-shot", "Amount of labelled data"), ("Task Order Ablation", "Task order"),
          ("Replay Ablation", "Replay"), ("Scaling Ablation", "Gradient scaling of the prompt-tuning strategy"),
          ("Equal Updates", "Amount of labelled data with the update count of the full split"),
          ("Joint Reference", "Upper reference: joint fine-tuning")]
CHANGED = {"lora_rank": "rank", "lr": "learning rate", "train_seed": "seed", "epochs": "epochs"}


def reported_runs():
    with open(INDEX_FILE, newline="", encoding="utf-8") as f:
        return [r for r in csv.DictReader(f) if r["role"] and r["role"] != "excluded"
                and r["has_eval_matrix"] == "yes"]


def roles(run):
    return [x for x in run["role"].split(";") if x]


def ids_tex(ids):
    key = lambda i: (0, int(i)) if i.isdigit() else (1, i)   # AeroPath IDs are numbers
    return ", ".join(i.replace("_", r"\_") for i in sorted(ids, key=key))


def volumes_table(runs) -> str:
    sets: dict[int, set] = {}
    for r in runs:
        if not r["train_max_cases"]:
            continue
        k = int(r["train_max_cases"])
        for task in sorted((REPO / r["path"] / "tasks").glob("task_[0-9][0-9]_*")):
            ids = set()
            for line in (task / "logs" / "run.log").read_text(encoding="utf-8", errors="replace").splitlines():
                m = DATA_RE.search(line)
                if m:
                    ids.add(m.group(1))
            if len(ids) != k:
                raise SystemExit(f"{r['label']} {task.name}: {len(ids)} volumes logged, expected {k}")
            if sets.setdefault(k, ids) != ids:
                raise SystemExit(f"{r['label']} {task.name}: different training set for k = {k}")
    ks = sorted(sets)
    for a, b in zip(ks, ks[1:]):
        if not sets[a] <= sets[b]:
            raise SystemExit(f"few-shot sets not nested: {a} vs {b}")
    test_skm, test_aero = set(), set()
    with open(TABLES / "per_volume_dice.csv", newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            (test_aero if row["row_task"] == "aeropath" else test_skm).add(row["case_id"])
    lines = [HEADER, r"\small", r"\begin{tabularx}{\linewidth}{@{}l>{\raggedright\arraybackslash}X@{}}",
             r"\toprule", r"Set & Volumes \\", r"\midrule"]
    for k in ks:
        new = sets[k] - (sets[ks[ks.index(k) - 1]] if ks.index(k) else set())
        note = "" if not ks.index(k) else rf" (the {ks[ks.index(k) - 1]} volumes above and {ids_tex(new)})"
        body = ids_tex(sets[k]) if not ks.index(k) else note.strip()[1:-1]
        lines.append(rf"SKM-TEA training, $k = {k}$ & {body} \\")
    lines.append(rf"SKM-TEA test ({len(test_skm)} volumes) & {ids_tex(test_skm)} \\")
    lines.append(rf"AeroPath test ({len(test_aero)} volumes) & {ids_tex(test_aero)} \\")
    lines += [r"\bottomrule", r"\end{tabularx}"]
    return "\n".join(lines) + "\n"


def run_name(r) -> str:
    name = STRATEGY[r["strategy"]][0].replace("Seq. fine-tuning", "Sequential fine-tuning")
    name = name.replace("Distillation-based", "Distillation-based strategy").replace(
        "Prompt tuning", "Prompt-tuning strategy")
    parts = []
    if r["lora_rank"]:
        parts.append(f"$r = {r['lora_rank']}$")
    if "Convergence Diagnosis" in roles(r):
        base = {"lora_rank": "4", "lr": "0.0001", "train_seed": "42", "epochs": "10"}
        diff = [k for k in base if r[k] != base[k]]
        parts.append("patellar cartilage only")
        if diff:
            k = diff[0]
            text = {"lora_rank": "", "lr": r"learning rate $3 \cdot 10^{-4}$" if r["lr"] == "0.0003" else f"learning rate {r['lr']}",
                    "train_seed": f"seed {r['train_seed']}", "epochs": f"{r['epochs']} epochs"}[k]
            parts.append(text)
        else:
            parts.append("settings of the sequence")
    else:
        unit = "structure" if r["task_order"] == "joint" else "task"   # joint fine-tuning has one stage, no tasks
        parts.append(f"{r['train_max_cases']} volumes per {unit}" if r["train_max_cases"] else "full training split")
        if r["task_order"] != "joint":                     # joint fine-tuning has no task order
            parts.append(f"{r['task_order']} task order")
        if r["epochs"] != "10":
            parts.append(f"{r['epochs']} epochs per task")
        if r["replay_fraction"]:
            parts.append(rf"replay $\rho = {float(r['replay_fraction']):g}$")
        if "Scaling Ablation" in roles(r):
            parts.append("gradient scaling inactive")
        if r["eval_checkpoint"] == "best_model.pt":
            parts.append("best validation checkpoint")
    return name + " (" + ", ".join(p for p in parts if p) + ")"


def matrix_table(r) -> str:
    rows = list(csv.reader(open(REPO / r["path"] / "eval_matrix.csv", encoding="utf-8")))
    head, body = rows[0], rows[1:]
    stages = ["Pre."] + [TASK_SHORT[h.replace("After ", "")] for h in head[2:]]
    order = [h.replace("After ", "") for h in head[2:]]
    lines = [r"\noindent\begin{minipage}{\linewidth}\centering\small",
             rf"\captionof{{table}}{{Evaluation matrix: {run_name(r)}; run \texttt{{{r['experiment_id'].replace('_', r'\_')}}}.}}",
             r"\setlength{\tabcolsep}{5pt}",
             rf"\begin{{tabular}}{{l{'r' * len(stages)}}}", r"\toprule",
             "Task & " + " & ".join(stages) + r" \\", r"\midrule"]
    for row in body:
        task = row[0].split(" ")[0]
        vals = [float(v) for v in row[1:]]
        cells = []
        for j, v in enumerate(vals):
            s = f"{v:.3f}"
            # Bold: the entry right after the task's own training stage (diagonal a_{i,i}).
            if task in order and j == order.index(task) + 1:
                s = rf"\textbf{{{s}}}"
            cells.append(s)
        label = TASK_SHORT[task] if "(CL)" in row[0] else "Ctrl"
        if "(CL)" not in row[0]:
            lines.append(r"\midrule")
        lines.append(f"{label} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{minipage}", r"\par\bigskip"]
    return "\n".join(lines)


def matrices(runs) -> str:
    out = [HEADER, r"\captionsetup{list=no}"]
    done = set()
    for role, title in GROUPS:
        def diag_key(r):
            # Diagnosis: settings of the sequence first, then rank, learning rate, seed, epochs (as Table 6.5).
            base = {"lora_rank": "4", "lr": "0.0001", "train_seed": "42", "epochs": "10"}
            diff = [k for k in base if r[k] != base[k]]
            return list(base).index(diff[0]) + 1 if diff else 0

        group = sorted([r for r in runs if role in roles(r) and r["experiment_id"] not in done],
                       key=lambda r: (diag_key(r) if role == "Convergence Diagnosis" else 0,
                                      STRATEGY_ORDER.index(r["strategy"]), int(r["lora_rank"] or 0),
                                      r["task_order"], int(r["train_max_cases"] or 999)))
        if not group:
            continue
        out.append(rf"\subsection*{{{title}}}")
        for r in group:
            out.append(matrix_table(r))
            done.add(r["experiment_id"])
    out.append(r"\captionsetup{list=yes}")
    return "\n".join(out) + "\n"


def main():
    runs = reported_runs()
    for name, tex in [("appA_volumes", volumes_table(runs)), ("appA_matrices", matrices(runs))]:
        (TABLES / f"{name}.tex").write_text(tex, encoding="utf-8")
        print(f"Wrote thesis/tables/{name}.tex")


if __name__ == "__main__":
    main()
