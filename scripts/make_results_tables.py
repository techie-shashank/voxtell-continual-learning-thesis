"""Write one LaTeX table body per experiment group to thesis/tables/.

Input:  thesis/tables/cl_metrics.csv and results/experiment_index.csv.
Output: thesis/tables/ch6_<group>.tex, each a bare `tabular` (booktabs). Caption
        and label belong in the chapter text:
            \\begin{table}[tb]\\centering \\input{tables/ch6_main} \\caption{...} \\end{table}

Values are point estimates (mean Dice over the test volumes), 3 decimals. The
bootstrap variability is in cl_metrics.csv and in the figures (error bars).

Usage (from the repository root):
    python scripts/make_results_tables.py
"""
from __future__ import annotations

from _results import (METRICS, TABLES, counterpart, load, roles, strategy_name,
                      train_volumes, value, STRATEGY_ORDER)

HEADER = {
    "adaptation": r"Adapt.\,$\uparrow$",
    "average_performance": r"Avg.\,$\uparrow$",
    "final_performance": r"Final\,$\uparrow$",
    "final_forgetting": r"Forg.\,$\downarrow$",
    "transfer": r"Transf.\,$\uparrow$",
    "control_drop": r"Ctrl.\ drop\,$\downarrow$",
}


def fmt(v) -> str:
    if v is None:
        return "--"
    s = f"{v:.3f}"
    if s == "-0.000":
        s = "0.000"
    return s.replace("-", "$-$")


def table(key_header: str | None, body: list[tuple[str, str, dict]], reference: list[tuple[str, str, dict]]) -> str:
    cols = "l" + ("l" if key_header else "") + "r" * len(METRICS)
    head = ["Strategy"] + ([key_header] if key_header else []) + [HEADER[m] for m in METRICS]
    # \small and the column spacing stay local to the surrounding table environment.
    lines = ["% Generated by scripts/make_results_tables.py from thesis/tables/cl_metrics.csv. Do not edit.",
             r"\small\setlength{\tabcolsep}{" + ("3pt" if key_header else "4pt") + "}",
             rf"\begin{{tabular}}{{{cols}}}", r"\toprule", " & ".join(head) + r" \\", r"\midrule"]

    def row(name, key, run):
        cells = [name] + ([key] if key_header else []) + [fmt(value(run, m)) for m in METRICS]
        return " & ".join(cells) + r" \\"

    lines += [row(*b) for b in body]
    if reference:
        lines.append(r"\midrule")
        lines += [row(*r) for r in reference]
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


def by_strategy(run):
    return (STRATEGY_ORDER.index(run["strategy"]), int(run["lora_rank"] or 0))


def main():
    runs, refs = load()
    ref_orig = ("Pretrained model", "", refs["original"])
    tables = {}

    main_runs = sorted([r for r in runs if "Main" in roles(r)], key=by_strategy)
    tables["main"] = table(None, [(strategy_name(r), "", r) for r in main_runs], [ref_orig])

    rank_runs = sorted([r for r in runs if "Rank Ablation" in roles(r)], key=lambda r: int(r["lora_rank"]))
    tables["rank"] = table("Rank $r$", [(strategy_name(r, with_rank=False), r["lora_rank"], r) for r in rank_runs],
                           [ref_orig])

    order_body = []
    for r in sorted([r for r in runs if "Task Order Ablation" in roles(r)], key=by_strategy):
        base = counterpart(r, runs)
        order_body += [(strategy_name(base), "Original", base), (strategy_name(r), "Reverse", r)]
    tables["task_order"] = table("Task order", order_body,
                                 [("Pretrained model", "Original", refs["original"]),
                                  ("Pretrained model", "Reverse", refs["reverse"])])

    few = [r for r in runs if "Few-shot" in roles(r)]
    few_body = []
    for strategy_runs in sorted({(r["strategy"], r["lora_rank"]) for r in few},
                                key=lambda k: STRATEGY_ORDER.index(k[0])):
        group = [r for r in few if (r["strategy"], r["lora_rank"]) == strategy_runs]
        group.append(counterpart(group[0], runs))
        for r in sorted(group, key=train_volumes):
            few_body.append((strategy_name(r), str(train_volumes(r)), r))
    tables["few_shot"] = table("Volumes", few_body, [ref_orig])

    replay_body = []
    for r in [r for r in runs if "Replay Ablation" in roles(r)]:
        base = counterpart(r, runs)
        replay_body += [(strategy_name(base), "none", base),
                        (strategy_name(r), f"{float(r['replay_fraction']):g}", r)]
    tables["replay"] = table("Replay", replay_body, [ref_orig])

    for name, tex in tables.items():
        path = TABLES / f"ch6_{name}.tex"
        path.write_text(tex, encoding="utf-8")
        print(f"Wrote {path.relative_to(TABLES.parents[1])}")


if __name__ == "__main__":
    main()
