"""Write one LaTeX table body per experiment group to thesis/tables/.

Input:  thesis/tables/cl_metrics.csv and results/experiment_index.csv.
Output: thesis/tables/ch6_<group>.tex, each a bare `tabular` (booktabs). Caption
        and label belong in the chapter text:
            \\begin{table}[tb]\\centering \\input{tables/ch6_main} \\caption{...} \\end{table}

Values are point estimates (mean Dice over the test volumes), 3 decimals. The
bootstrap variability is in cl_metrics.csv and in the figures (error bars).
Metrics that are not defined for a run (Adaptation, Final Forgetting and Transfer of
joint fine-tuning, which has no task sequence) are shown as "--".

Tables use the main evaluation of each run (parameters after the last epoch for all reruns
of October 2026), except ch6_components, which also shows the tagged evaluations
(best_validation, weight_ensemble) of the same runs.

Usage (from the repository root):
    python scripts/make_results_tables.py
"""
from __future__ import annotations

from _results import (HIGHER_IS_BETTER, METRICS, TABLES, counterpart, load, roles, strategy_name,
                      train_volumes, value, STRATEGY_ORDER)

# Task-specific LoRA evaluates the control task with the pretrained model and each trained task with its
# own adapter, so these two values are zero or near zero by construction (Sec. 5.3.2). They are marked
# with a dagger and never bolded (decision 2026-11-04).
BY_CONSTRUCTION = {"final_forgetting", "control_drop"}


def by_construction(run, metric) -> bool:
    return run["strategy"] == "lora" and metric in BY_CONSTRUCTION

HEADER = {
    "adaptation": r"Adapt.\,$\uparrow$",
    "average_performance": r"Avg.\,$\uparrow$",
    "final_performance": r"Final\,$\uparrow$",
    "final_forgetting": r"Forg.\,$\downarrow$",
    "transfer": r"Transf.\,$\uparrow$",
    "control_drop": r"Ctrl.\ drop\,$\downarrow$",
}


def fmt(v) -> str:
    if v is None:
        return "--"
    s = f"{v:.3f}"
    if s == "-0.000":
        s = "0.000"
    return s.replace("-", "$-$")


def best_cells(body, groups) -> set[tuple[int, str]]:
    """(row index, metric) of the best value per column within each group of body rows (ties: all)."""
    out = set()
    for group in groups:
        for m in METRICS:
            vals = {k: round(value(body[k][2], m), 3) for k in group
                    if value(body[k][2], m) is not None and not by_construction(body[k][2], m)}
            if len(vals) < 2:
                continue
            best = (max if HIGHER_IS_BETTER[m] else min)(vals.values())
            out |= {(k, m) for k, v in vals.items() if v == best}
    return out


def table(key_header: str | None, body: list[tuple[str, str, dict]], reference: list[tuple[str, str, dict]],
          extra: list[tuple[str, str, dict]] | None = None, bold_groups: list[list[int]] | None = None) -> str:
    cols = "l" + ("l" if key_header else "") + "r" * len(METRICS)
    head = ["Strategy"] + ([key_header] if key_header else []) + [HEADER[m] for m in METRICS]
    # \small and the column spacing stay local to the surrounding table environment.
    lines = ["% Generated by scripts/make_results_tables.py from thesis/tables/cl_metrics.csv. Do not edit.",
             r"\small\setlength{\tabcolsep}{" + ("3pt" if key_header else "4pt") + "}",
             rf"\begin{{tabular}}{{{cols}}}", r"\toprule", " & ".join(head) + r" \\", r"\midrule"]

    bold = best_cells(body, bold_groups or [])

    def cell(run, m, k=None):
        c = fmt(value(run, m))
        if (k, m) in bold:
            c = r"\textbf{" + c + "}"
        if by_construction(run, m):
            c += r"$^{\dagger}$"
        return c

    def row(name, key, run, k=None):
        cells = [name] + ([key] if key_header else []) + [cell(run, m, k) for m in METRICS]
        return " & ".join(cells) + r" \\"

    # A small gap between groups of rows of the same strategy (few-shot, task order, rank tables).
    for k, b in enumerate(body):
        if key_header and k and b[0] != body[k - 1][0]:
            lines.append(r"\addlinespace")
        lines.append(row(*b, k=k))
    # A separate group below the body, e.g. replay in the main table (not comparable on the control task).
    if extra:
        lines.append(r"\midrule")
        lines += [row(*e) for e in extra]
    if reference:
        lines.append(r"\midrule")
        lines += [row(*r) for r in reference]
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


def updates_per_task(run) -> int:
    return int(run["epochs"]) * train_volumes(run)


def eval_name(run, evaluation: str) -> str:
    """Name of the evaluated parameters of one evaluation of a run."""
    if evaluation == "weight_ensemble":
        return "weight ensemble"
    if evaluation == "best_validation" or run["eval_checkpoint"] == "best_model.pt":
        return "best validation"
    return "last epoch"


def by_strategy(run):
    return (STRATEGY_ORDER.index(run["strategy"]), int(run["lora_rank"] or 0))


def main():
    runs, refs = load()
    ref_orig = ("Pretrained model", "", refs["original"])
    tables = {}

    main_runs = sorted([r for r in runs if "Main" in roles(r)], key=by_strategy)
    # Shared LoRA + replay is one of the six strategies and follows shared LoRA, the order of Ch. 5.3
    # (thesis_notes.md §1, 2026-11-01). The asterisk (explained in the caption) marks a run whose
    # memory holds control-task volumes (index column replay_control_volumes = yes, the run before the
    # reruns); the rerun of October 2026 keeps the control task out of the memory (thesis_notes.md §1).
    replay_runs = [r for r in runs if "Replay Ablation" in roles(r)]
    star = lambda r: r"$^{*}$" if r["replay_control_volumes"] != "no" else ""
    main_body = []
    for r in main_runs:
        main_body.append((strategy_name(r), "", r))
        if r["strategy"] == "shared_lora":
            main_body += [(strategy_name(x).replace("Shared LoRA", "Shared LoRA + replay") + star(x), "", x)
                          for x in replay_runs]
    tables["main"] = table(None, main_body, [ref_orig], bold_groups=[list(range(len(main_body)))],
                           extra=[("Joint fine-tuning (upper reference)", "", r) for r in runs
                                  if "Joint Reference" in roles(r) and not r["train_max_cases"]])

    # Rank ablation: shared LoRA r = 4 ... 2048 and task-specific LoRA r = 4, 8, grouped by strategy.
    rank_runs = sorted([r for r in runs if "Rank Ablation" in roles(r)],
                       key=lambda r: (STRATEGY_ORDER.index(r["strategy"]), int(r["lora_rank"])))
    rank_body = [(strategy_name(r, with_rank=False), r["lora_rank"], r) for r in rank_runs]
    tables["rank"] = table("Rank $r$", rank_body, [ref_orig],
                           bold_groups=[[k for k, b in enumerate(rank_body) if b[2]["strategy"] == "shared_lora"]])

    order_body = []
    for r in sorted([r for r in runs if "Task Order Ablation" in roles(r)], key=by_strategy):
        base = counterpart(r, runs)
        order_body += [(strategy_name(base), "Original", base), (strategy_name(r), "Reverse", r)]
    tables["task_order"] = table("Task order", order_body,
                                 [("Pretrained model", "Original", refs["original"]),
                                  ("Pretrained model", "Reverse", refs["reverse"])])

    # Few-shot runs, the equal-updates runs (k = 5 with the update count of the full split) and the
    # full-split counterpart of each strategy; key column: training volumes and updates per task.
    few = [r for r in runs if "Few-shot" in roles(r) or "Equal Updates" in roles(r)]
    few_body = []
    for strategy_runs in sorted({(r["strategy"], r["lora_rank"]) for r in few},
                                key=lambda k: STRATEGY_ORDER.index(k[0])):
        group = [r for r in few if (r["strategy"], r["lora_rank"]) == strategy_runs]
        group.append(counterpart(group[0], runs))
        for r in sorted(group, key=lambda r: (train_volumes(r), updates_per_task(r))):
            key = f"{train_volumes(r)} ({updates_per_task(r):,})".replace(",", "{,}")
            few_body.append((strategy_name(r), key, r))
    # Joint fine-tuning: one stage on all six structures (6k samples per epoch), so no updates per task;
    # the total number of updates of its stage is shown instead (2026-11-05; 6,480 for the full split
    # matches train_batches=648 x 10 epochs in SLURM log voxtell_1848501.out).
    joint = sorted([r for r in runs if "Joint Reference" in roles(r)], key=train_volumes)
    def joint_key(r):
        total = int(r["epochs"]) * 6 * train_volumes(r)
        return f"{train_volumes(r)} ({total:,} total)".replace(",", "{,}")
    tables["few_shot"] = table(r"Vol.\ (updates)", few_body, [ref_orig],
                               extra=[("Joint fine-tuning", joint_key(r), r) for r in joint])

    # Additional evaluations and component ablations of the strategies with a full-model or
    # prompt-tuning update: checkpoint (last epoch vs best validation), weight ensemble, gradient scaling.
    tagged = {ev: {r["experiment_id"]: r for r in load(ev)[0]} for ev in ("best_validation", "weight_ensemble")}
    comp_body = []
    for r in [r for r in main_runs if r["strategy"] in ("naive_sequential_finetuning", "zscl", "cpe_clip")]:
        name = strategy_name(r)
        # The last-epoch rows are in the main table; the appendix table lists only the additional evaluations
        # (decision 2026-11-04).
        for ev in ("best_validation", "weight_ensemble"):
            if r["experiment_id"] in tagged[ev]:
                comp_body.append((name, eval_name(r, ev), tagged[ev][r["experiment_id"]]))
        if r["strategy"] == "cpe_clip":
            for a in [a for a in runs if "Scaling Ablation" in roles(a)]:
                comp_body.append((name + " (no scaling)", eval_name(a, "main"), a))
    tables["components"] = table("Evaluation", comp_body, [ref_orig])

    # Replay table removed 2026-11-05: not included anywhere since replay is reported in Table 6.2 (Sec. 6.2).

    # Table of the patellar diagnosis removed 2026-11-05 (author decision): Fig. 6.3 and the prose of
    # Sec. 6.3 give all its values; the 50-epoch interval is quoted from cl_metrics.csv.

    for name, tex in tables.items():
        path = TABLES / f"ch6_{name}.tex"
        path.write_text(tex, encoding="utf-8")
        print(f"Wrote {path.relative_to(TABLES.parents[1])}")


if __name__ == "__main__":
    main()
